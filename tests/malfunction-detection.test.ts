// Mock helper functions
function calculateMockUptimePercentage(lastHeartbeat, registeredAt, currentTime) {
  const totalTime = currentTime - registeredAt
  if (totalTime === 0) return 100
  
  const downtime = currentTime - lastHeartbeat
  return Math.max(0, 100 - Math.floor((downtime * 100) / totalTime))
}

function determineMockHealthStatus(failureCount, uptimePercentage) {
  if (uptimePercentage < 50) return 3 // Offline
  if (uptimePercentage < 80) return 2 // Critical
  if (failureCount > 5 || uptimePercentage < 95) return 1 // Warning
  return 0 // Healthy
}
